W3 = np.exp(2j * np.pi / 3)
CUBE = np.array([1, W3, W3 ** 2])
TOL = 1e-7


# ------------------------------------------------------------- Paulis -----

def _digits(m):
    x = np.arange(3 ** m)
    return (x[:, None] // 3 ** (m - 1 - np.arange(m))[None, :]) % 3   # (dim, m)


def _canon_key(v):
    """Bytes identifying v up to a global phase (first nonzero entry made real
    positive); entries are exact roots of unity over a common modulus, so
    rounding to six places is stable."""
    j = np.flatnonzero(np.abs(v) > 1e-9)[0]
    w = v * (abs(v[j]) / v[j])
    return (np.round(w, 6) + 0.0).tobytes()


def _canon_columns(V):
    """Columns of V with their global phase fixed (first nonzero entry real
    positive), and the indices of one representative per distinct column."""
    nz = np.abs(V) > 1e-9
    first = np.argmax(nz, axis=0)
    ref = V[first, np.arange(V.shape[1])]
    W = V * (np.abs(ref) / ref)[None, :]
    keys = np.ascontiguousarray(np.round(W.T, 6) + 0.0).view(np.float64)
    _, idx = np.unique(keys, axis=0, return_index=True)
    return W, np.sort(idx)


def pauli_images(u, m):
    """One (Q u, Q^-1 u) pair per Pauli class Q mod the stabilizer of u.

    Q = X^a Z^c acts by (Q u)[x + a] = w3^(c.x) u[x]; Q^-1 = Z^-c X^-a acts
    by (Q^-1 u)[x] = w3^(-c.x) u[x + a]. Different representatives of a class
    give the same Q u and Q^-1 u up to phase, and the phase is absorbed by
    nu, so one representative per distinct Q u suffices. Returns exactly 3^m
    pairs (the Pauli group mod phase has 3^(2m) elements and Stab(u) has 3^m).
    """
    dim = 3 ** m
    digs = _digits(m)
    Cs = np.array(list(itertools.product(range(3), repeat=m)))            # (3^m, m)
    PH = W3 ** ((digs @ Cs.T) % 3)                                          # (dim, 3^m)
    QU, QINV = [], []
    for a in itertools.product(range(3), repeat=m):
        y = ((digs + np.array(a)) % 3) @ (3 ** (m - 1 - np.arange(m)))
        qu = np.zeros((dim, len(Cs)), dtype=complex)
        qu[y, :] = PH * u[:, None]
        QU.append(qu)
        QINV.append(np.conj(PH) * u[y][:, None])
    QU, QINV = np.concatenate(QU, axis=1), np.concatenate(QINV, axis=1)
    _, idx = _canon_columns(QU)
    if len(idx) != 3 ** m:
        raise AssertionError(f"{len(idx)} Pauli images of a state on {m} qutrits, expected {3 ** m}")
    return [(QU[:, k], QINV[:, k]) for k in idx]


# ------------------------------------------------------------- lifting -----

def _match_sums(L, R, rhs, tol=TOL, margin=1e-4):
    """Index pairs (l, r) with L[l] + R[r] = rhs within tol (entrywise), and a
    certified gap: every other pair misses rhs by at least the returned value.

    Keys are a random functional f; |f.(v - rhs)| <= |f| sqrt(dim) |v - rhs|_inf,
    so every pair within `margin` entrywise has its key inside a window of
    that width around the target, and pairs outside the window miss by more
    than margin. Inside the window every pair is checked in full."""
    rng = np.random.default_rng(5)
    f = rng.normal(size=L.shape[1]) + 1j * rng.normal(size=L.shape[1])
    kl = L @ f
    kr = (rhs[None, :] - R) @ f
    order = np.argsort(kl.real)
    kls = kl.real[order]
    window = margin * np.linalg.norm(f) * np.sqrt(L.shape[1])
    lo = np.searchsorted(kls, kr.real - window, side="left")
    hi = np.searchsorted(kls, kr.real + window, side="right")
    rows = np.flatnonzero(hi > lo)
    counts = hi[rows] - lo[rows]
    rs = np.repeat(rows, counts)
    starts = np.repeat(lo[rows], counts)
    offs = np.arange(len(rs)) - np.repeat(np.cumsum(counts) - counts, counts)
    ls = order[starts + offs]
    # the imaginary part of the key obeys the same bound, so filter on it too
    near = np.abs(kl[ls].imag - kr[rs].imag) <= window
    ls, rs = ls[near], rs[near]
    out = []
    gap = margin
    step = 1 << 16
    for k in range(0, len(rs), step):
        l_blk, r_blk = ls[k:k + step], rs[k:k + step]
        dist = np.abs(L[l_blk] + R[r_blk] - rhs).max(axis=1)
        hit = dist < tol
        out += [(int(l), int(r)) for l, r in zip(l_blk[hit], r_blk[hit])]
        if (~hit).any():
            gap = min(gap, float(dist[~hit].min()))
    return out, gap


def _sum_table(arrays):
    """All sums of one row from each array, with the mixed-radix combo index
    decoded by `_decode`."""
    S = arrays[0]
    for A in arrays[1:]:
        S = (S[:, None, :] + A[None, :, :]).reshape(-1, S.shape[1])
    return S


def _decode(idx, sizes):
    out = []
    for n in reversed(sizes):
        out.append(idx % n)
        idx //= n
    return list(reversed(out))


def lifts(dec_states, dec_coeffs, alpha, target_m, m, tol=TOL):
    """Every lift of the minimal decomposition target_m = sum d_i u_i of
    phi^m, taken as slice k = 1, to a rank-r decomposition of phi^(m+1).

    Returns a list of lifts, each a list of r stabilizer vectors of dimension
    3^(m+1), and the number of slice-2 matches examined.
    """
    r = len(dec_states)
    a0, a1, a2 = (complex(x) for x in alpha)
    rhs2 = (a2 / a1) * target_m
    rhs0 = (a0 / a1) * target_m
    imgs = [pauli_images(u, m) for u in dec_states]
    # slice-2 options: d_i mu Q u, one row per (class, mu)
    opts2 = [np.array([d * mu * qu for qu, _ in im for mu in CUBE]) for d, im in zip(dec_coeffs, imgs)]
    sizes = [len(o) for o in opts2]
    half = max(1, r // 2)
    L = _sum_table(opts2[:half])
    R = _sum_table(opts2[half:]) if r > half else np.zeros((1, len(target_m)), dtype=complex)
    matches, floor = _match_sums(L, R, rhs2, tol)
    found = []
    for l, rr in matches:
        combo = _decode(l, sizes[:half]) + (_decode(rr, sizes[half:]) if r > half else [])
        cls = [c // 3 for c in combo]
        mus = [CUBE[c % 3] for c in combo]
        # slice 0: sum d_i nu_i Q_i^-1 u_i = rhs0 with nu_i cube roots. This is
        # brute-forced over the 3^r assignments rather than solved, because
        # rhs0 vanishes when alpha_0 = 0 (the strange state) and the
        # equation is then homogeneous.
        Qinv = np.column_stack([d * imgs[i][cls[i]][1] for i, d in enumerate(dec_coeffs)])
        NU = np.array(list(itertools.product(CUBE, repeat=r))).T          # (r, 3^r)
        err = np.abs(Qinv @ NU - rhs0[:, None]).max(axis=0)
        for gcol in np.flatnonzero(err < tol):
            nu = NU[:, gcol]
            terms = []
            for i in range(r):
                qu, qinv = imgs[i][cls[i]]
                terms.append(np.concatenate((nu[i] * qinv, dec_states[i], mus[i] * qu)))
            found.append(terms)
    return found, (len(matches), floor)


def confirm_lift(terms, alpha, target_m):
    """Residual of the best fit of phi (x) phi^m by the lifted terms, and a
    check that every term is a stabilizer state (it lies in the dictionary is
    not checked here; it is a stabilizer state by construction, see the
    module docstring)."""
    psi = np.kron(np.asarray(alpha, dtype=complex), target_m)
    A = np.column_stack(terms)
    x, *_ = np.linalg.lstsq(A, psi, rcond=None)
    return float(np.linalg.norm(A @ x - psi))


# ------------------------------------------------- enumerating decompositions

def decompositions_with_pivot(psi, D, i, rank, partners=None, rng=None, workers=1, members=None,
                              least_partner=True):
    """Every minimal rank-`rank` decomposition of psi (rank 2, 3 or 4) that
    contains dictionary state i and, for rank 4, a partner from `partners`
    (default: every other state), as sorted index tuples.

    Minimal means no proper subset of the states spans psi. When chi(psi)
    equals `rank`, which the certificates establish first, every
    decomposition is minimal and the list is complete. A state whose image
    modulo span(psi, s_i, s_j) vanishes lies in a rank-3 span of psi and is
    dropped, so non-minimal four-sets are not listed systematically.

    With `least_partner` (the default, and always in the compiled kernel)
    the two remaining members are searched above the partner's index, the
    partner being the least non-pivot member; `least_partner=False` is the
    numpy reference without that restriction, for tests.

    Rank 4 quotients out psi, s_i and the partner s_j, then collects pairs
    whose images are parallel. Such a pair (a, b) has s_a - c s_b in
    span(psi, s_i, s_j); it is a decomposition exactly when the psi
    coefficient is nonzero, i.e. when s_a and s_b are not also parallel
    modulo span(s_i, s_j) alone. That second test is one small Gram matrix
    per group, and survivors are confirmed by an exact solve. The random
    projection can only lose speed, not decompositions: parallel vectors
    stay parallel under any linear map, and every candidate is checked in
    the full space.
    """
    rng = rng or np.random.default_rng(11)
    psi = psi / np.linalg.norm(psi)
    N, dim = D.shape[1], D.shape[0]
    R = rng.normal(size=(PROJ_DIM, dim)) + 1j * rng.normal(size=(PROJ_DIM, dim))
    B1, _ = np.linalg.qr(np.column_stack((psi, D[:, i])))
    q1 = D - B1 @ (B1.conj().T @ D)
    n1 = np.linalg.norm(q1, axis=0)
    found = set()

    def confirm(cols):
        A = D[:, list(cols)]
        if np.linalg.matrix_rank(A, tol=1e-8) < len(cols):
            return False
        x, *_ = np.linalg.lstsq(A, psi, rcond=None)
        return np.linalg.norm(A @ x - psi) < 1e-9

    if rank == 2:
        for j in np.flatnonzero(n1 < 1e-7):
            if j != i and confirm((i, int(j))):
                found.add(tuple(sorted((int(i), int(j)))))
        return sorted(found)
    if rank == 3:
        keep = n1 > 1e-7
        keep[i] = False
        ids = np.flatnonzero(keep)
        U = R @ q1[:, ids]
        U /= np.linalg.norm(U, axis=0)
        groups, _ = _parallel_groups(U, rng)
        for g in groups:
            gi = ids[g]
            for a in range(len(gi)):
                for b in range(a + 1, len(gi)):
                    cols = tuple(sorted((int(i), int(gi[a]), int(gi[b]))))
                    if confirm(cols):
                        found.add(cols)
        return sorted(found)
    if rank != 4:
        raise ValueError("rank must be 2, 3 or 4")
    # rank 4: the pivot's projection modulo span(s_i) only, for the psi-coefficient test
    e_i = D[:, i] / np.linalg.norm(D[:, i])
    p1 = D - np.outer(e_i, e_i.conj() @ D)
    partners = np.arange(N) if partners is None else np.asarray(partners)
    partners = partners[(partners != i) & (n1[partners] > 1e-7)]
    allowed = np.ones(N, bool) if members is None else np.zeros(N, bool)
    if members is not None:
        allowed[np.asarray(members)] = True
    ctx = dict(D=D, psi=psi, i=int(i), q1=q1, n1=n1, p1=p1, R=R, RQ1=R @ q1, RP1=R @ p1,
               np1=np.linalg.norm(p1, axis=0), allowed=allowed, rng_seed=int(rng.integers(1 << 31)),
               least_partner=bool(least_partner))
    if workers and workers > 1 and len(partners) >= 4 * workers:
        import multiprocessing as mp
        global _CTX
        _CTX = ctx
        chunks = np.array_split(partners, 4 * workers)
        with mp.get_context("fork").Pool(workers) as pool:
            for part in pool.imap_unordered(_rank4_partners, chunks):
                found.update(part)
        _CTX = None
    else:
        found.update(_rank4_partners_ctx(ctx, partners))
    return sorted(found)


_CTX = None


def _rank4_partners(chunk):
    return _rank4_partners_ctx(_CTX, chunk)


def _native_kernel():
    """The compiled pivot-pair search from stabrank_core, or None."""
    if os.environ.get("STABRANK_NO_NATIVE"):
        return None
    try:
        from stabrank.stabrank_core import rank4_pivot_partners
    except ImportError:
        return None
    return rank4_pivot_partners


def _rank4_partners_native(c, chunk, kernel):
    """The same search as `_rank4_partners_ctx`, in C++ (cpp/src/pivot_pair.cpp)."""
    D = np.ascontiguousarray(c["D"], dtype=np.complex128)
    psi = np.ascontiguousarray(c["psi"], dtype=np.complex128)
    out = kernel(D, psi, int(c["i"]), np.ascontiguousarray(chunk, dtype=np.int64),
                 np.ascontiguousarray(c["allowed"], dtype=np.uint8), PROJ_DIM, c["rng_seed"])
    return {tuple(int(x) for x in row) for row in np.asarray(out)}


def _rank4_partners_ctx(c, chunk):
    """Rank-4 decompositions {i, j, a, b} for every partner j in `chunk`.

    Dispatches to the compiled kernel when stabrank_core provides it (set
    STABRANK_NO_NATIVE=1 to force this numpy reference, which the tests
    compare against the kernel).

    Modulo span(psi, s_i, s_j) the images of s_a and s_b must be parallel;
    modulo span(s_i, s_j) alone they must not be (else the quadruple is
    dependent and psi is absent). Both tests run on the same random
    projection: the second as a sub-grouping of each parallel group by the
    canonical key of the second quotient, so a group contributes only its
    cross-key pairs. Survivors are confirmed by an exact solve.
    """
    kernel = _native_kernel() if c.get("least_partner", True) else None
    if kernel is not None:
        return _rank4_partners_native(c, chunk, kernel)
    D, psi, i = c["D"], c["psi"], c["i"]
    q1, n1, p1, R, RQ1, RP1, np1 = c["q1"], c["n1"], c["p1"], c["R"], c["RQ1"], c["RP1"], c["np1"]
    rng = np.random.default_rng(c["rng_seed"])
    can = rng.normal(size=R.shape[0]) + 1j * rng.normal(size=R.shape[0])
    key = rng.normal(size=R.shape[0]) + 1j * rng.normal(size=R.shape[0])
    found = set()

    def confirm(cols):
        A = D[:, list(cols)]
        if np.linalg.matrix_rank(A, tol=1e-8) < len(cols):
            return False
        x, *_ = np.linalg.lstsq(A, psi, rcond=None)
        return np.linalg.norm(A @ x - psi) < 1e-9

    for j in chunk:
        j = int(j)
        v = q1[:, j] / n1[j]
        w = v.conj() @ q1
        nq2 = np.sqrt(np.maximum(n1 ** 2 - np.abs(w) ** 2, 0))
        keep = (nq2 > 1e-7) & c["allowed"]
        keep[i] = False
        if c.get("least_partner", True):
            keep[:j + 1] = False                # the partner is the least non-pivot member
        else:
            keep[j] = False
        ids = np.flatnonzero(keep)
        U = RQ1[:, ids] - np.outer(R @ v, w[ids])
        U /= np.linalg.norm(U, axis=0)
        groups, _ = _parallel_groups(U, rng)
        if not groups:
            continue
        # second quotient, modulo span(s_i, s_j) only, as keys
        f = p1[:, j] / np1[j]
        wf = f.conj() @ p1[:, ids]
        U2 = RP1[:, ids] - np.outer(R @ f, wf)
        n2 = np.linalg.norm(U2, axis=0)
        for g in groups:
            gi = ids[g]
            V2 = U2[:, g]
            ng = n2[g]
            small = ng < 1e-7 * np.maximum(1, np1[gi])
            k2 = (key @ V2) / np.where(small, 1, can @ V2)
            # pairs whose second-quotient keys differ are the candidates;
            # a pair with equal keys is confirmed parallel by its overlap
            same_key = np.abs(k2[:, None] - k2[None, :]) < 1e-6 * (1 + np.abs(k2[:, None]))
            ov = np.abs(V2.conj().T @ V2)
            parallel2 = same_key & (np.abs(ov - ng[:, None] * ng[None, :]) < 1e-6 * ng[:, None] * ng[None, :])
            cand = ~parallel2 & ~small[:, None] & ~small[None, :]
            for a, b in np.argwhere(np.triu(cand, 1)):
                cols = tuple(sorted((i, j, int(gi[a]), int(gi[b]))))
                if confirm(cols):
                    found.add(cols)
    return found
    return sorted(found)


def stabilizer_orbit_labels(perms, i, max_points=400, stabilizer_order=None):
    """Orbit labels on the dictionary under a subgroup of the stabilizer of
    state i in the group generated by the permutations `perms`.

    Schreier's lemma: with a transversal T_a (T_a(i) = a) over the orbit of
    i, the elements T_{g(a)}^-1 g T_a generate the stabilizer. Only the
    Schreier generators from the first `max_points` orbit points are used,
    which generate a subgroup; its orbits are finer than the stabilizer's,
    so using one partner per orbit stays sound and merely does more work.
    Orbits are the connected components of the union of the generators'
    permutation graphs. When the stabilizer's order is known (group order
    over orbit size) the transversal is cut to about thirty points per
    element of it, since a handful of Schreier generators already generate
    a small stabilizer and a trivial one needs none.
    """
    if stabilizer_order is not None:
        if stabilizer_order <= 1:
            return np.arange(len(perms[0])), 0
        max_points = int(min(max_points, max(40, 30 * stabilizer_order)))
    from scipy.sparse import coo_matrix
    from scipy.sparse.csgraph import connected_components
    N = len(perms[0])
    trans = {int(i): np.arange(N)}
    frontier = [int(i)]
    while frontier and len(trans) < max_points:
        nxt = []
        for a in frontier:
            for p in perms:
                b = int(p[a])
                if b not in trans:
                    trans[b] = p[trans[a]]          # (p o T_a)(x) = p[T_a[x]]
                    nxt.append(b)
        frontier = nxt
    trans_inv = {a: np.argsort(T) for a, T in trans.items()}
    gens, seen = [], set()
    ident = np.arange(N)
    for a, Ta in trans.items():
        for p in perms:
            b = int(p[a])
            if b in trans:
                sgen = trans_inv[b][p[Ta]]
                if sgen[i] != i:
                    raise AssertionError("Schreier generator does not fix the pivot")
                h = sgen.tobytes()
                if h not in seen and not np.array_equal(sgen, ident):
                    seen.add(h)
                    gens.append(sgen)
    if not gens:
        return ident.copy(), 0
    rows = np.concatenate([ident] * len(gens))
    cols = np.concatenate(gens)
    graph = coo_matrix((np.ones(len(rows), dtype=np.int8), (rows, cols)), shape=(N, N))
    _, labels = connected_components(graph, directed=False)
    return labels, len(gens)


def all_decompositions(orbit, m, rank, D=None, verbose=True, workers=1):
    """One member of every unitary-symmetry orbit of rank-`rank`
    decompositions of |M>^m (and possibly more), with the pivot list used.
    The dictionary is the one on the width * m qudits the copies occupy."""
    import time
    from stabrank_verify import ORBIT_P, orbit_qudits
    D = dictionary(ORBIT_P[orbit], orbit_qudits(orbit, m)) if D is None else D
    psi = psi_for(orbit, m)
    reps, info = symmetry_orbit_reps(orbit, m, D, antiunitary=False)
    if verbose:
        print(f"{orbit} m={m}: {D.shape[1]} states, unitary symmetry group of order "
              f"{info['order']}, {info['orbits']} pivot orbits", flush=True)
    # A decomposition is a multiset of orbits; move a member of its lowest
    # orbit (by representative index) to the pivot and the other members lie
    # in orbits with representative index at least the pivot's. So partners
    # can be restricted to those states.
    # Within a pivot, a symmetry h fixing the pivot carries decompositions
    # containing (pivot, partner) to ones containing (pivot, h(partner)).
    # Choose h to minimise the least index among the non-pivot members: that
    # member is then minimal in its orbit under the stabilizer and every
    # other member has a larger index. So the partners are one state per
    # stabilizer orbit (its least index) and the remaining two members are
    # searched above the partner; all of them lie in orbits at or above the
    # pivot's, since the pivot is the least orbit of the decomposition.
    roots = info["roots"]
    out = set()
    for n, i in enumerate(np.sort(reps)):
        t = time.time()
        partners = None
        note = ""
        members = None
        if rank == 4:
            orbit_size = int(np.count_nonzero(roots == i))
            labels, ngens = stabilizer_orbit_labels(info["perms"], int(i),
                                                    stabilizer_order=info["order"] // orbit_size)
            cand = np.flatnonzero(roots >= i)
            _, first = np.unique(labels[cand], return_index=True)
            partners = cand[first]
            members = cand
            note = f", {len(partners)} partners of {len(cand)}"
        decs = decompositions_with_pivot(psi, D, int(i), rank, partners=partners, workers=workers,
                                         members=members)
        out.update(decs)
        if verbose:
            print(f"  pivot {n + 1}/{len(reps)} (state {i}): {len(decs)} decompositions{note}, "
                  f"{time.time() - t:.1f}s", flush=True)
    return sorted(out), reps


# ------------------------------------------------------------- qubits ------

FOURTH = np.array([1, 1j, -1, -1j])


def pauli_images_qubit(u, m):
    """One Q u per Pauli class Q mod the stabilizer of u, for Q = X^a Z^c on
    m qubits acting by (Q u)[x xor a] = (-1)^(c.x) u[x]. Exactly 2^m images."""
    dim = 1 << m
    x = np.arange(dim)
    par = np.array([[bin(c & t).count("1") % 2 for c in range(dim)] for t in x])   # (dim, dim)
    PH = (-1.0) ** par
    QU = []
    for a in range(dim):
        qu = np.zeros((dim, dim), dtype=complex)
        qu[x ^ a, :] = PH * u[:, None]
        QU.append(qu)
    QU = np.concatenate(QU, axis=1)
    _, idx = _canon_columns(QU)
    if len(idx) != dim:
        raise AssertionError(f"{len(idx)} Pauli images of a state on {m} qubits, expected {dim}")
    return [QU[:, k] for k in idx]


def lifts_qubit(dec_states, dec_coeffs, alpha, target_m, m, tol=TOL):
    """Qubit version of `lifts`. With phi = alpha_0 |0> + alpha_1 |1>, both
    nonzero, a rank-r decomposition of phi^(m+1) sliced along the first qubit
    has slice 0 a minimal decomposition (d_i, u_i) of phi^m and slice 1 equal
    to mu_i Q_i u_i termwise, with Q_i a Pauli and mu_i a fourth root of
    unity: the stabilizer group of the term contains lambda X Z^b (x) Q_i
    (or the term is a product beta (x) v with beta of full support), and
    lambda^2 (X Z^b)^2 Q_i^2 = I forces lambda^4 = 1. Conversely
    |0> u + |1> mu Q u is a controlled-Pauli image of (|0> + mu |1>) (x) u,
    hence a stabilizer state. So the lift condition is the single matching
        sum_i d_i mu_i Q_i u_i = (alpha_1 / alpha_0) phi^m.
    """
    r = len(dec_states)
    a0, a1 = (complex(x) for x in alpha)
    rhs = (a1 / a0) * target_m
    imgs = [pauli_images_qubit(u, m) for u in dec_states]
    opts = [np.array([d * mu * qu for qu in im for mu in FOURTH]) for d, im in zip(dec_coeffs, imgs)]
    sizes = [len(o) for o in opts]
    half = max(1, r // 2)
    L = _sum_table(opts[:half])
    R = _sum_table(opts[half:]) if r > half else np.zeros((1, len(target_m)), dtype=complex)
    matches, floor = _match_sums(L, R, rhs, tol)
    found = []
    for l, rr in matches:
        combo = _decode(l, sizes[:half]) + (_decode(rr, sizes[half:]) if r > half else [])
        terms = [np.concatenate((dec_states[i], FOURTH[c % 4] * imgs[i][c // 4]))
                 for i, c in enumerate(combo)]
        found.append(terms)
    return found, (len(matches), floor)


# ------------------------------------------------------------- blocks ------

def lifts_qubit_block(dec_states, dec_coeffs, alpha, target_m, n, width, tol=TOL,
                      max_combos=1 << 20, stats=None):
    """Block version of `lifts_qubit` for a qubit orbit of width w (CS: w = 2),
    whose m copies live on n = w m qubits.

    Let |M> on w qubits have amplitudes alpha_x, x in F_2^w, all nonzero, let
    r = chi(|M>^m), and suppose |M>^(m+1) = sum_i c_i s_i with r stabilizer
    terms. Slice along the whole first copy, u_i^(x) = (<x| (x) I) s_i.

      (a) alpha_x |M>^m = sum_i c_i u_i^(x) for every x, so every slice is a
          minimal decomposition of |M>^m and no u_i^(x) vanishes;
      (b) the x with u_i^(x) != 0 form a coset of the X-part of the image of
          Stab(s_i) in the symplectic coordinates of the first block, so by
          (a) that image projects onto all of F_2^w: for every a there is
          lambda_a X^a Z^(c_a) (x) Q_i^(a) in Stab(s_i), and applying it to
          s_i gives u_i^(a) = mu_i^(a) Q_i^(a) u_i^(0) with Q_i^(a) a Pauli on
          n qubits and mu_i^(a) a fourth root of unity (the element squares
          to a phase times I, and that phase is 1, so lambda_a^4 = 1).

    So with slice 0 taken as the decomposition (d_i, u_i), d_i = c_i/alpha_0,
    a lift needs for each a != 0 Pauli classes mod Stab(u_i) and phases with

        sum_i d_i mu_i^(a) Q_i^(a) u_i = (alpha_a / alpha_0) |M>^m,

    one matching per a, each the meet in the middle of `lifts_qubit`. If any
    of the 2^w - 1 matchings has no solution the decomposition does not lift.
    The matchings are solved independently and say nothing about whether the
    Paulis chosen for different slices are compatible, so a choice of one
    solution per a assembles s_i = sum_a |a> (x) mu_i^(a) Q_i^(a) u_i, which
    reproduces |M>^(m+1) but is a stabilizer state only when they are; every
    assembled term is tested with `to_witness.term_from_vector` and a lift is
    returned only when all r terms pass. That test is load-bearing. Whenever
    every ratio alpha_a / alpha_0 is a fourth root of unity, as for CS (the
    ratios are 1, 1, i), the identity assignment Q_i = I, mu_i = alpha_a /
    alpha_0 solves every slice equation of every base decomposition, the
    slice equations alone exclude nothing, and the candidate |M> (x) u_i is
    rejected exactly because |M> is not a stabilizer state; a lift then
    exists only through a non-identity solution of some slice equation. With
    width 1 this is `lifts_qubit` with the extra test.

    Returns (lifts, (matches, floor)) like `lifts_qubit`: `lifts` are the
    assembled decompositions whose terms are all stabilizer states, `matches`
    the number of slice solutions examined over all a, and `floor` the
    certified miss of every rejected Pauli assignment (capped at the search
    window of `_match_sums`). When `stats` is a dict it is filled with
    `matches` (solutions per slice, in order of a), `identity_only` (every
    solution of every slice is the identity class on every term),
    `candidates` (assembled) and `rejected` (assembled terms that failed the
    stabilizer test, as (candidate, term, reason)).
    """
    from to_witness import NotStabilizer, term_from_vector
    r = len(dec_states)
    a_vec = [complex(x) for x in alpha]
    if len(a_vec) != 1 << width:
        raise ValueError(f"alpha has {len(a_vec)} amplitudes, expected {1 << width}")
    if any(abs(x) < 1e-12 for x in a_vec):
        raise ValueError("the block lift needs every amplitude of the orbit state nonzero")
    imgs = [pauli_images_qubit(u, n) for u in dec_states]
    opts = [np.array([d * mu * qu for qu in im for mu in FOURTH]) for d, im in zip(dec_coeffs, imgs)]
    sizes = [len(o) for o in opts]
    half = max(1, r // 2)
    L = _sum_table(opts[:half])
    R = _sum_table(opts[half:]) if r > half else np.zeros((1, len(target_m)), dtype=complex)
    if stats is not None:
        stats.update({"matches": [], "identity_only": True, "candidates": 0, "rejected": []})
    sols, nmatch, floor = [], 0, float("inf")
    for a in range(1, 1 << width):
        rhs = (a_vec[a] / a_vec[0]) * target_m
        matches, fl = _match_sums(L, R, rhs, tol)
        nmatch += len(matches)
        floor = min(floor, fl)
        combos = [_decode(l, sizes[:half]) + (_decode(rr, sizes[half:]) if r > half else [])
                  for l, rr in matches]
        if stats is not None:
            stats["matches"].append(len(combos))
            # class 0 of pauli_images_qubit is the identity (a = 0, c = 0)
            stats["identity_only"] &= all(c // 4 == 0 for combo in combos for c in combo)
        if not combos:
            return [], (nmatch, floor)       # slice a has no Pauli assignment: no lift
        sols.append(combos)
    total = 1
    for c in sols:
        total *= len(c)
    if total > max_combos:
        raise RuntimeError(f"{total} slice-solution combinations to assemble; refusing to decide")
    found = []
    for k, choice in enumerate(itertools.product(*sols)):
        if stats is not None:
            stats["candidates"] += 1
        terms = []
        for i in range(r):
            slices = [dec_states[i]] + [FOURTH[c[i] % 4] * imgs[i][c[i] // 4] for c in choice]
            s_i = np.concatenate(slices)
            try:
                term_from_vector(s_i, 2, n + width)
            except NotStabilizer as exc:
                if stats is not None:
                    stats["rejected"].append((k, i, str(exc)))
                break
            terms.append(s_i)
        else:
            found.append(terms)
    return found, (nmatch, floor)


def _lifter(orbit):
    """The slice-and-lift matcher for an orbit, with the call signature
    f(states, coeffs, alpha, target, n) -> (lifts, (matches, floor)) where n
    is the number of qudits the states live on."""
    from stabrank_verify import ORBIT_P, ORBIT_WIDTH
    p, w = ORBIT_P[orbit], ORBIT_WIDTH.get(orbit, 1)
    if p == 3:
        if w != 1:
            raise ValueError("the block lift is implemented for qubits only")
        return lifts
    if p != 2:
        raise ValueError(f"no slice-and-lift matcher for p = {p}")
    if w == 1:
        return lifts_qubit
    return functools.partial(lifts_qubit_block, width=w)


def lift_all(orbit, m, decs, D, verbose=True, stats_out=None):
    """Lift every decomposition in `decs` (index tuples into D) one copy up.
    Returns the list of lifted term lists; every lift is confirmed against
    phi (x) phi^m and a failure raises. For a block orbit the per-decomposition
    statistics of `lifts_qubit_block` are printed (the number of solutions of
    each slice equation and the fate of every assembled candidate, which is
    where such a lift is decided) and appended to `stats_out` when given."""
    from stabrank_verify import ORBIT_WIDTH, orbit_state, orbit_qudits
    alpha = np.array([complex(x) for x in orbit_state(orbit)]).ravel()
    psi = psi_for(orbit, m)
    lifter = _lifter(orbit)
    n = orbit_qudits(orbit, m)
    width = ORBIT_WIDTH.get(orbit, 1)
    lifted, floor = [], float("inf")
    for k, cols in enumerate(decs):
        states = [D[:, c] for c in cols]
        d, *_ = np.linalg.lstsq(np.column_stack(states), psi, rcond=None)
        if np.linalg.norm(np.column_stack(states) @ d - psi) > 1e-9:
            raise AssertionError("a listed decomposition does not reproduce the target")
        if width > 1:
            st = {}
            L, (nmatch, fl) = lifter(states, d, alpha, psi, n, stats=st)
            if stats_out is not None:
                stats_out.append(st)
            if verbose:
                print("  " + describe_block_lift(cols, st, width, k + 1, len(decs)), flush=True)
        else:
            L, (nmatch, fl) = lifter(states, d, alpha, psi, n)
        floor = min(floor, fl)
        for terms in L:
            res = confirm_lift(terms, alpha, psi)
            if res > 1e-8:
                raise AssertionError(f"a lift failed its confirmation, residual {res:.2e}")
            lifted.append(terms)
    if verbose:
        print(f"{orbit} m={m} -> {m + 1}: {len(decs)} decompositions, {len(lifted)} lifts"
              + (f"; every other Pauli assignment misses its slice equation by more than "
                 f"the {floor:.0e} search window" if floor < float("inf") else ""), flush=True)
    return lifted


def describe_block_lift(cols, st, width, k=None, total=None):
    """One line on the fate of a base decomposition under the block lift."""
    head = f"decomposition {k}/{total} " if k is not None else "decomposition "
    head += "(states " + ", ".join(str(c) for c in cols) + "): "
    if len(st["matches"]) < (1 << width) - 1:
        a = len(st["matches"])
        return head + (f"slice {a + 1:0{width}b} has no Pauli assignment after "
                       f"{', '.join(str(x) for x in st['matches'])} on the earlier slices; no lift")
    body = "slice equations have " + ", ".join(str(x) for x in st["matches"]) + " solution(s)"
    if st["identity_only"]:
        body += " (the identity assignment only, so the candidate terms are |M> (x) u_i)"
    rej = st["rejected"]
    nrej = len({c for c, _, _ in rej})
    body += f"; {st['candidates']} candidate(s) assembled, {nrej} rejected"
    if rej:
        reasons = sorted({r for _, _, r in rej})
        body += " by the stabilizer test on the assembled terms (" + "; ".join(reasons) + ")"
    kept = st["candidates"] - nrej
    body += f"; {kept} lift(s)"
    return head + body


def lift_chain(orbit, m0, rank, m_target, workers=1, verbose=True):
    """Enumerate the rank-`rank` decompositions of |M>^m0 up to unitary
    symmetry and lift them copy by copy to m_target.

    Returns (counts, gap): counts[m] is the number of rank-`rank`
    decompositions held at m copies (representatives at m0, all lifts
    above), and gap is the smallest certified miss of a rejected Pauli
    assignment over the chain. counts[m_target] == 0 means
    chi(|M>^m_target) > rank, given chi(|M>^m) == rank for m0 <= m < m_target.
    """
    from stabrank_verify import orbit_state, ORBIT_P, orbit_qudits
    p = ORBIT_P[orbit]
    D = dictionary(p, orbit_qudits(orbit, m0))
    decs, _ = all_decompositions(orbit, m0, rank, D, verbose=verbose, workers=workers)
    counts = {m0: len(decs)}
    current = lift_all(orbit, m0, decs, D, verbose=verbose)
    counts[m0 + 1] = len(current)
    alpha = np.array([complex(x) for x in orbit_state(orbit)]).ravel()
    lifter = _lifter(orbit)
    gap = float("inf")
    for m in range(m0 + 1, m_target):
        psi = psi_for(orbit, m)
        nxt = []
        for terms in current:
            A = np.column_stack(terms)
            d, *_ = np.linalg.lstsq(A, psi, rcond=None)
            if np.linalg.norm(A @ d - psi) > 1e-9:
                raise AssertionError("a lifted decomposition does not reproduce the target")
            L, (_, g) = lifter(terms, d, alpha, psi, orbit_qudits(orbit, m))
            gap = min(gap, g)
            for t in L:
                if confirm_lift(t, alpha, psi) > 1e-8:
                    raise AssertionError("a lift failed its confirmation")
            nxt.extend(L)
        if verbose:
            print(f"{orbit} m={m} -> {m + 1}: {len(current)} decompositions, {len(nxt)} lifts"
                  + (f"; every rejected Pauli assignment misses by at least {gap:.2e}"
                     if gap < float("inf") else ""), flush=True)
        current = nxt
        counts[m + 1] = len(current)
    return counts, gap


